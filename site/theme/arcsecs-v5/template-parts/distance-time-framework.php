            <h2 id="distance-time-clockless-title">Why local clocks are treated as probes.</h2>
            <p>A cesium clock, atomic oscillator, particle decay process, or local timing device may be extremely precise, but it is still made from matter. If local conditions change the behavior of the particles inside that device, ArcSecs treats the device as changed.</p>
