            <h2 id="distance-time-lightyears-title">Why ArcSecs does not start with lightyears.</h2>
            <p>A lightyear sounds like a distance unit, but it depends on a stable electromagnetic light speed and a trusted time measurement. That is useful in standard astronomy, but ArcSecs is testing a different foundation. If electromagnetic propagation can vary with distance, medium density, energy degeneration, or path conditions, then light travel distance should not be the primary ruler.</p>
            <p>ArcSecs treats lightyears as legacy comparison labels only. The preferred distance foundation is geometric and relational: parallax, parsecs, arcseconds, angular geometry, proper motion, gravitational-wave standard sirens, and dark standard-siren matching.</p>
